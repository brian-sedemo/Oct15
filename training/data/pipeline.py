@dataclass
class PermafrostMixture:
    mixture: dict[str, float]
    seq_len: int = 8192
    seed: int = 1331

    def __post_init__(self):
        total = sum(self.mixture.values())
        if abs(total - 1.0) > 1e-6:
            raise ValueError(f"Permafrost mixture must sum to 1.0, got {total:.4f}")

    def manifest_uris(self) -> dict[str, str]:
        """Resolve each source to its sharded manifest in the data lake."""
        return {
            name: f"s3://nimbus-permafrost/v4/{name}/manifest.jsonl"
            for name in self.mixture
        }


